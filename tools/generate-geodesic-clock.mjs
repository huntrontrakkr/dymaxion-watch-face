// Samples the Geodesic numeral skeletons once and writes the approved pixel
// masters plus the native minute-flip lattice. Needs the Playwright browser.
import {build} from 'esbuild';
import {chromium} from '@playwright/test';
import {mkdirSync, writeFileSync} from 'node:fs';
const compiled = await build({stdin: {contents: `
import {rasterizeGeodesicGlyph, GEODESIC_MASK_BYTES} from './shared/geodesic-numerals.js';
const glyphs = Array.from({length: 10}, (_, digit) => {
  const glyph = rasterizeGeodesicGlyph(String(digit)), bits = new Uint8Array(GEODESIC_MASK_BYTES);
  for (let i = 0; i < glyph.length; i++) if (glyph[i]) bits[i >> 3] |= 1 << (i & 7);
  return [...bits];
});
window.clockAssets = {glyphs};
`, resolveDir: process.cwd(), sourcefile: 'generate-geodesic.js'}, bundle: true, write: false, format: 'iife'});
const browser = await chromium.launch();
let data;
try { const page = await browser.newPage(); await page.addScriptTag({content: compiled.outputFiles[0].text}); data = await page.evaluate(() => window.clockAssets); }
finally { await browser.close(); }
mkdirSync('assets/type', {recursive: true});
writeFileSync('assets/type/geodesic-clock.json', JSON.stringify(data.glyphs) + '\n');

// The lattice is pure arithmetic, so Node computes it directly. Browser and
// watch then share one table: cell geometry in Q8, plus per-row owner runs.
const {GEODESIC_METRICS: M} = await import('../shared/geodesic-numerals.js');
const {flipGrid} = await import('../shared/minute-flip.js');
const grid = flipGrid('geodesic'), rows = [], boundaries = [];
for (let y = 0; y < M.height; y++) {
  const first = grid.membership[y * M.width];
  if (first < 0) throw new Error(`Row ${y} starts outside the lattice.`);
  const row = {first, offset: boundaries.length, count: 0};
  for (let x = 1; x < M.width; x++) {
    const id = grid.membership[y * M.width + x], previous = grid.membership[y * M.width + x - 1];
    if (id === previous) continue;
    // Ids rise along a row; the watch stores each change and its step.
    if (id <= previous || id - previous > 255) throw new Error(`Row ${y} owner steps from ${previous} to ${id} at x=${x}.`);
    boundaries.push([x, id - previous]); row.count++;
  }
  rows.push(row);
}
for (let y = 0; y < M.height; y++) for (let x = 0, id = rows[y].first, k = 0; x < M.width; x++) {
  while (k < rows[y].count && boundaries[rows[y].offset + k][0] <= x) { id += boundaries[rows[y].offset + k][1]; k++; }
  if (id !== grid.membership[y * M.width + x]) throw new Error(`Owner runs disagree at ${x},${y}.`);
}
// One raw resource, loaded into the heap only while Geodesic figures are shown:
// the static app image stays inside Pebble's 64 KB process limit.
const BIAS = 8192, cellBytes = 10, rowBytes = 6, glyphBytes = data.glyphs[0].length;
const cellsAt = 10 * glyphBytes, rowsAt = cellsAt + grid.cells.length * cellBytes, boundariesAt = rowsAt + M.height * rowBytes;
const total = boundariesAt + boundaries.length * 2, out = Buffer.alloc(total);
data.glyphs.forEach((g, i) => Buffer.from(g).copy(out, i * glyphBytes));
const u16 = (v, at, what) => { if (!Number.isInteger(v) || v < 0 || v > 0xffff) throw new Error(`${what} out of range: ${v}`); out.writeUInt16LE(v, at); };
grid.cells.forEach((c, i) => {
  const at = cellsAt + i * cellBytes;
  if (c.nx * c.nx + c.ny * c.ny !== c.length2) throw new Error('Cell length must be derivable on the watch.');
  u16(c.ax + BIAS, at, 'ax'); u16(c.ay + BIAS, at + 2, 'ay'); out.writeInt16LE(c.nx, at + 4); out.writeInt16LE(c.ny, at + 6);
  u16(c.centerX + BIAS, at + 8, 'centerX');
});
rows.forEach((r, y) => {
  const at = rowsAt + y * rowBytes;
  u16(r.first, at, 'first'); u16(r.offset, at + 2, 'offset'); out.writeUInt8(r.count, at + 4);
});
// Boundaries hold x and the owner relative to the row's first cell, so the
// watch can binary-search a row instead of scanning it.
rows.forEach(r => { let id = r.first; for (let k = 0; k < r.count; k++) {
  const [x, step] = boundaries[r.offset + k]; id += step;
  if (id - r.first > 255) throw new Error('Row spans too many cells.');
  out.writeUInt8(x, boundariesAt + (r.offset + k) * 2); out.writeUInt8(id - r.first, boundariesAt + (r.offset + k) * 2 + 1);
} });
mkdirSync('watchface/resources/data', {recursive: true});
writeFileSync('watchface/resources/data/clock-geodesic.bin', out);
mkdirSync('watchface/src/c/generated', {recursive: true});
writeFileSync('watchface/src/c/generated/geodesic_clock_sizes.h', [
  '// Generated by tools/generate-geodesic-clock.mjs. Layout of resources/data/clock-geodesic.bin.',
  '#pragma once',
  `#define GEODESIC_HEIGHT ${M.height}`, `#define GEODESIC_CAP_TOP ${M.capTop}`, `#define GEODESIC_CAP_HEIGHT ${M.capHeight}`,
  `#define GEODESIC_DIGIT_WIDTH ${M.digitWidth}`, `#define GEODESIC_STARTS {${M.starts.join(',')}}`,
  `#define GEODESIC_COLON_X ${M.colonX}`, `#define GEODESIC_COLON_TOPS {${M.colonTops.join(',')}}`,
  `#define GEODESIC_GLYPH_BYTES ${glyphBytes}`, `#define GEODESIC_CELL_COUNT ${grid.cells.length}`,
  `#define GEODESIC_CELLS_AT ${cellsAt}`, `#define GEODESIC_ROWS_AT ${rowsAt}`, `#define GEODESIC_BOUNDARIES_AT ${boundariesAt}`,
  `#define GEODESIC_BYTES ${total}`, `#define GEODESIC_BIAS ${BIAS}`, ''
].join('\n'));
console.log(`Generated Geodesic clock: ${10 * glyphBytes} glyph bytes, ${grid.cells.length} tiles, ${boundaries.length} owner boundaries; resource ${total} bytes.`);
