import {build} from 'esbuild';
import {chromium} from '@playwright/test';
import {mkdirSync, writeFileSync} from 'node:fs';
const compiled = await build({stdin: {contents: `
import {rasterizeBroadGlyph} from './shared/broad-numerals.js';
import {flipGrid, FLIP_SCALE} from './shared/minute-flip.js';
const glyphs = Array.from({length:10}, (_, digit) => {
  const glyph = rasterizeBroadGlyph(String(digit)), bits = new Uint8Array(180);
  for(let i=0;i<glyph.length;i++)if(glyph[i])bits[i>>3]|=1<<(i&7);
  return [...bits];
});
const grid=flipGrid();
window.clockAssets={glyphs, scales:FLIP_SCALE, owners:[...grid.membership],
  cells:grid.cells.map(c=>[c.cx,c.cy])};
`, resolveDir: process.cwd(), sourcefile: 'generate-clock.js'}, bundle: true, write: false, format: 'iife'});
const browser = await chromium.launch();
let data;
try { const page = await browser.newPage(); await page.addScriptTag({content: compiled.outputFiles[0].text}); data = await page.evaluate(() => window.clockAssets); }
finally { await browser.close(); }
mkdirSync('watchface/src/c/generated', {recursive: true});
mkdirSync('assets/type', {recursive: true});
writeFileSync('assets/type/broad-clock.json', JSON.stringify(data.glyphs) + '\n');
writeFileSync('watchface/src/c/generated/broad_clock_sizes.h', `// Generated by tools/generate-broad-clock.mjs\n#pragma once\n#define CLOCK_CELL_COUNT ${data.cells.length}\n`);
const lines = values => Array.from({length: Math.ceil(values.length / 32)}, (_, i) => values.slice(i * 32, i * 32 + 32).join(',') + ',');
writeFileSync('watchface/src/c/generated/broad_clock_data.h', [
  '// Generated by tools/generate-broad-clock.mjs. Rounded pixel masters and Q8 tile centroids.',
  'static const uint8_t CLOCK_GLYPHS[10][180]={', ...data.glyphs.map(g => '{' + g.join(',') + '},'), '};',
  'static const uint16_t CLOCK_SCALES[33]={' + data.scales.join(',') + '};',
  'static const uint8_t CLOCK_OWNERS[8000]={', ...lines(data.owners), '};',
  'static const ClockCell CLOCK_CELLS[CLOCK_CELL_COUNT]={', ...data.cells.map(c => '{' + c.join(',') + '},'), '};', ''
].join('\n'));
if (data.cells.length > 255) throw new Error('Owner table stores tile ids in one byte.');
console.log('Generated rounded clock: 1,800 glyph bytes, ' + data.cells.length + ' equilateral tiles, 400 ms transition.');
