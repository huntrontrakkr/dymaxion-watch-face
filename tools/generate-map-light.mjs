// Bounds for relighting only what can change (watchface/src/c/map_light.c).
// From the baked map (map-0.bin), for each 8×8 tile holding map pixels, and
// each 2×2 sub-tile within it: a centre direction C (the rounded mean of the
// stored directions) and r, the largest distance of any stored direction from
// C, rounded up. For a Sun S, every pixel's light N·S is then within
// S·C ± |S|r, so a tile or sub-tile whose range stays on one side of both
// thresholds needs no per-pixel work: the result is still exactly the
// per-pixel rule, because the bounds come from the stored directions
// themselves.
//
// map-light.bin: a header, the tile table, then one block per tile.
//   header: "ML", version 1, tile count (u16)
//   table entry (8 bytes): C (3 × i8), r (u8), block offset (u16), position
//     (u16: ty*25+tx in bits 0-8, the tile's map-pixel count in bits 9-15)
//   block: 32 bytes of flags (a nibble per pixel, row-major: bits 0-1 kind,
//     1 sea, 2 land, bit 2 edge), 16 sub-tile bounds (C, r; r 255 when empty),
//     then 3 bytes per map pixel, in sub-tile order, row-major within each.
import {readFileSync,writeFileSync} from 'node:fs';
export const TILE=8,SUB=2,W=200,H=104,TILES_X=W/TILE,TILES_Y=H/TILE;
const map=new Int8Array(readFileSync('watchface/resources/maps/map-0.bin'));
const flag=(x,y)=>map[(y*W+x)*4+3]&7,kind=(x,y)=>map[(y*W+x)*4+3]&3,normal=(x,y)=>[0,1,2].map(k=>map[(y*W+x)*4+k]);
function bound(points){
  if(!points.length)return [0,0,0,255];
  const C=[0,1,2].map(k=>Math.round(points.reduce((s,p)=>s+p[k],0)/points.length));
  const r=Math.ceil(Math.max(...points.map(p=>Math.hypot(p[0]-C[0],p[1]-C[1],p[2]-C[2]))));
  if(r>=255)throw new Error('bound too wide');
  return [...C,r];
}
const table=[],blocks=[];let offset=0;
for(let ty=0;ty<TILES_Y;ty++)for(let tx=0;tx<TILES_X;tx++){
  const pixels=[];
  for(let y=0;y<TILE;y++)for(let x=0;x<TILE;x++)if(kind(tx*TILE+x,ty*TILE+y))pixels.push(normal(tx*TILE+x,ty*TILE+y));
  if(!pixels.length)continue;
  const flags=new Uint8Array(TILE*TILE/2);
  for(let i=0;i<TILE*TILE;i++){const f=flag(tx*TILE+i%TILE,ty*TILE+(i/TILE|0))&(kind(tx*TILE+i%TILE,ty*TILE+(i/TILE|0))?7:0);flags[i>>1]|=f<<((i&1)*4);}
  const bounds=[],normals=[];
  for(let sy=0;sy<TILE;sy+=SUB)for(let sx=0;sx<TILE;sx+=SUB){
    const sub=[];
    for(let y=sy;y<sy+SUB;y++)for(let x=sx;x<sx+SUB;x++){const X=tx*TILE+x,Y=ty*TILE+y;if(kind(X,Y)){sub.push(normal(X,Y));normals.push(...normal(X,Y));}}
    bounds.push(...bound(sub));
  }
  const block=Uint8Array.from([...flags,...new Uint8Array(Int8Array.from(bounds).buffer),...new Uint8Array(Int8Array.from(normals).buffer)]);
  const [c0,c1,c2,r]=bound(pixels);
  table.push([c0,c1,c2,r,offset,ty*TILES_X+tx|pixels.length<<9]);blocks.push(block);offset+=block.length;
}
if(offset>65535)throw new Error('blocks exceed 16-bit offsets');
const out=new Uint8Array(6+table.length*8+offset),view=new DataView(out.buffer);
out[0]=77;out[1]=76;out[2]=1;out[3]=0;view.setUint16(4,table.length,true);
table.forEach(([c0,c1,c2,r,off,pos],i)=>{const o=6+i*8;view.setInt8(o,c0);view.setInt8(o+1,c1);view.setInt8(o+2,c2);out[o+3]=r;view.setUint16(o+4,off,true);view.setUint16(o+6,pos,true);});
let at=6+table.length*8;for(const b of blocks){out.set(b,at);at+=b.length;}
writeFileSync('watchface/resources/maps/map-light.bin',out);
writeFileSync('watchface/src/c/generated/map_light_sizes.h',`// Generated by tools/generate-map-light.mjs; do not edit.
#pragma once
#define MAP_LIGHT_TILES ${table.length}
#define MAP_LIGHT_TILE ${TILE}
#define MAP_LIGHT_SUB ${SUB}
#define MAP_LIGHT_TILES_X ${TILES_X}
#define MAP_LIGHT_TABLE 6
#define MAP_LIGHT_BLOCKS ${6+table.length*8}
`);
console.log(`map-light: ${table.length} tiles, ${out.length} bytes (table ${table.length*8}, blocks ${offset}).`);
