// Builds the Chamfer figures from the Draft zone numerals (tools/draft-lettering.py),
// writes the approved pixel masters and the native minute-transition lattice resource.
// Pure geometry: no browser is needed.
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
const source = readFileSync('tools/draft-lettering.py', 'utf8');
const zoneBlock = source.slice(source.indexOf('ZONE = {'), source.indexOf('}', source.indexOf('ZONE = {')));
const ZONE = Object.fromEntries([...zoneBlock.matchAll(/'(\d)': \[([^\]]*)\]/g)].map(([, d, rows]) => [d, [...rows.matchAll(/'([.#]+)'/g)].map(m => m[1])]));
if (Object.keys(ZONE).length !== 10) throw new Error('Expected ten zone numerals in tools/draft-lettering.py.');
const {chamferMaster, CHAMFER_MASK_BYTES} = await import('../shared/chamfer-numerals.js');
const data = {glyphs: Array.from({length: 10}, (_, digit) => {
  const mask = chamferMaster(ZONE[digit]), bits = new Uint8Array(CHAMFER_MASK_BYTES);
  for (let i = 0; i < mask.length; i++) if (mask[i]) bits[i >> 3] |= 1 << (i & 7);
  return [...bits];
})};
mkdirSync('assets/type', {recursive: true});
writeFileSync('assets/type/chamfer-clock.json', JSON.stringify(data.glyphs) + '\n');

// The lattice is pure arithmetic, so Node computes it directly. Browser and
// watch then share one table: tile centroids in Q8, plus per-row owner runs.
const {CHAMFER_METRICS: M, colonDot} = await import('../shared/chamfer-numerals.js');
const colonRows = Array.from({length: M.colonWidth}, (_, y) => Array.from({length: M.colonWidth}, (_, x) => colonDot(x, y) ? 1 << x : 0).reduce((a, b) => a | b, 0));
const {flipGrid} = await import('../shared/minute-flip.js');
const grid = flipGrid('chamfer'), rows = [], boundaries = [];
for (let y = 0; y < M.height; y++) {
  const first = grid.membership[y * M.width];
  if (first < 0) throw new Error(`Row ${y} starts outside the lattice.`);
  const row = {first, offset: boundaries.length, count: 0};
  for (let x = 1; x < M.width; x++) {
    const id = grid.membership[y * M.width + x], previous = grid.membership[y * M.width + x - 1];
    if (id === previous) continue;
    // Ids rise along a row; the watch stores each change and its step.
    if (id <= previous || id - previous > 255) throw new Error(`Row ${y} owner steps from ${previous} to ${id} at x=${x}.`);
    boundaries.push([x, id - previous]); row.count++;
  }
  rows.push(row);
}
for (let y = 0; y < M.height; y++) for (let x = 0, id = rows[y].first, k = 0; x < M.width; x++) {
  while (k < rows[y].count && boundaries[rows[y].offset + k][0] <= x) { id += boundaries[rows[y].offset + k][1]; k++; }
  if (id !== grid.membership[y * M.width + x]) throw new Error(`Owner runs disagree at ${x},${y}.`);
}
// One raw resource, loaded into the heap only while Chamfer figures are shown:
// the static app image stays inside Pebble's 64 KB process limit.
const BIAS = 8192, cellBytes = 4, rowBytes = 6, glyphBytes = data.glyphs[0].length;
const cellsAt = 10 * glyphBytes, rowsAt = cellsAt + grid.cells.length * cellBytes, boundariesAt = rowsAt + M.height * rowBytes;
const total = boundariesAt + boundaries.length * 2, out = Buffer.alloc(total);
data.glyphs.forEach((g, i) => Buffer.from(g).copy(out, i * glyphBytes));
const u16 = (v, at, what) => { if (!Number.isInteger(v) || v < 0 || v > 0xffff) throw new Error(`${what} out of range: ${v}`); out.writeUInt16LE(v, at); };
grid.cells.forEach((c, i) => {
  const at = cellsAt + i * cellBytes;
  u16(c.cx + BIAS, at, 'cx'); u16(c.cy + BIAS, at + 2, 'cy');
});
rows.forEach((r, y) => {
  const at = rowsAt + y * rowBytes;
  u16(r.first, at, 'first'); u16(r.offset, at + 2, 'offset'); out.writeUInt8(r.count, at + 4);
});
// Boundaries hold x and the owner relative to the row's first cell, so the
// watch can binary-search a row instead of scanning it.
rows.forEach(r => { let id = r.first; for (let k = 0; k < r.count; k++) {
  const [x, step] = boundaries[r.offset + k]; id += step;
  if (id - r.first > 255) throw new Error('Row spans too many cells.');
  out.writeUInt8(x, boundariesAt + (r.offset + k) * 2); out.writeUInt8(id - r.first, boundariesAt + (r.offset + k) * 2 + 1);
} });
mkdirSync('watchface/resources/data', {recursive: true});
writeFileSync('watchface/resources/data/clock-chamfer.bin', out);
mkdirSync('watchface/src/c/generated', {recursive: true});
writeFileSync('watchface/src/c/generated/chamfer_clock_sizes.h', [
  '// Generated by tools/generate-chamfer-clock.mjs. Layout of resources/data/clock-chamfer.bin.',
  '#pragma once',
  `#define CHAMFER_HEIGHT ${M.height}`, `#define CHAMFER_CAP_TOP ${M.capTop}`, `#define CHAMFER_CAP_HEIGHT ${M.capHeight}`,
  `#define CHAMFER_DIGIT_WIDTH ${M.digitWidth}`, `#define CHAMFER_STARTS {${M.starts.join(',')}}`,
  `#define CHAMFER_COLON_X ${M.colonX}`, `#define CHAMFER_COLON_TOPS {${M.colonTops.join(',')}}`,
  `#define CHAMFER_COLON_WIDTH ${M.colonWidth}`, `#define CHAMFER_COLON_ROWS {${colonRows.join(',')}}`,
  `#define CHAMFER_GLYPH_BYTES ${glyphBytes}`, `#define CHAMFER_CELL_COUNT ${grid.cells.length}`,
  `#define CHAMFER_CELLS_AT ${cellsAt}`, `#define CHAMFER_ROWS_AT ${rowsAt}`, `#define CHAMFER_BOUNDARIES_AT ${boundariesAt}`,
  `#define CHAMFER_BYTES ${total}`, `#define CHAMFER_BIAS ${BIAS}`, ''
].join('\n'));
console.log(`Generated Chamfer clock: ${10 * glyphBytes} glyph bytes, ${grid.cells.length} tiles, ${boundaries.length} owner boundaries; resource ${total} bytes.`);
