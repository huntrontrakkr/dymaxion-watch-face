import {chromium, expect} from '@playwright/test';
import {resolve} from 'node:path';
import {mkdirSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const base=process.env.PREVIEW_URL||'http://127.0.0.1:4174';
const browser=await chromium.launch(),reports=[];
mkdirSync('test-results',{recursive:true});
try {
  const page=await browser.newPage({viewport:{width:1000,height:900},timezoneId:'America/New_York'}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.clock.install({time:new Date('2026-09-23T16:33:58Z')});
  await page.clock.pauseAt(new Date('2026-09-23T16:33:59Z'));
  await page.goto(base);await page.waitForFunction(()=>document.querySelector('#preview-time').textContent.includes('LIVE'));
  await page.locator('#reset').click();
  const screen=page.locator('#screen');
  const clock=()=>screen.evaluate(c=>[...c.getContext('2d').getImageData(0,18,200,40).data]);
  assert.equal(await screen.getAttribute('data-clock-display'),'broad');
  assert.equal(await screen.getAttribute('data-clock-animating'),'false');
  const before=await clock();
  await page.clock.runFor(1002);
  assert.equal(await screen.getAttribute('data-clock-animating'),'true','minute boundary starts the flip');
  await page.clock.runFor(180);const middle=await clock();assert.notDeepEqual(middle,before);
  await screen.screenshot({path:'test-results/clock-minute-flip-midpoint.png',animations:'allow'});
  await page.clock.runFor(250);
  assert.equal(await screen.getAttribute('data-clock-animating'),'false','the last tile must finish within 400 ms plus one display frame');
  const after=await clock();assert.notDeepEqual(after,middle);assert.notDeepEqual(after,before);
  await page.clock.runFor(5000);assert.deepEqual(await clock(),after,'idle clock must not continue animating');
  await page.emulateMedia({reducedMotion:'reduce'});await page.clock.runFor(60000);
  assert.equal(await screen.getAttribute('data-clock-animating'),'false');assert.notDeepEqual(await clock(),after);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.getByRole('tab',{name:'Character',exact:true}).click();await page.locator('#motion').uncheck();
  await page.clock.runFor(60000);assert.equal(await screen.getAttribute('data-clock-animating'),'false');
  await page.locator('#motion').check();await page.locator('#scrub').fill('1');
  assert.equal(await screen.getAttribute('data-clock-animating'),'false','scrubbing is a discontinuity, not a minute tick');
  await page.locator('#live').click();assert.equal(await screen.getAttribute('data-clock-animating'),'false');
  await page.reload();await page.waitForFunction(()=>document.querySelector('#preview-time').textContent.includes('LIVE'));
  assert.equal(await screen.getAttribute('data-clock-display'),'broad');
  assert.deepEqual(errors,[]);reports.push({liveMinute:true,reducedMotion:true,motionDisabled:true,idleStable:true,errors});
  await page.close();
  for(const [width,scheme] of [[736,'light'],[390,'light'],[320,'dark']]){
    const page=await browser.newPage({viewport:{width,height:1000},colorScheme:scheme}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.clock.install({time:new Date('2026-09-23T16:33:58Z')});await page.clock.pauseAt(new Date('2026-09-23T16:33:59Z'));
    await page.goto('file://'+resolve('output/minute-flip-study/preview.html'));
    const frame=page.frames().find(f=>f!==page.mainFrame());await frame.waitForSelector('[data-replay]');
    const root=frame.locator('#dymaxion-minute-flip-study'),png=()=>frame.locator('[data-animation]').evaluate(c=>c.toDataURL());
    assert.equal(await root.getAttribute('data-running'),'false');const original=await png();
    await frame.getByRole('button',{name:'Replay 400 ms'}).click();await page.clock.runFor(180);
    assert.equal(await root.getAttribute('data-running'),'true');assert.notEqual(await png(),original);
    await page.clock.runFor(240);assert.equal(await root.getAttribute('data-running'),'false');assert.equal(await root.getAttribute('data-elapsed'),'400');
    assert.equal(await png(),await frame.locator('[data-after]').evaluate(c=>c.toDataURL()));
    await frame.getByLabel('Minute change',{exact:true}).selectOption('23:59');
    await frame.getByLabel('Animation position',{exact:true}).fill('200');
    await frame.getByLabel('Show changing triangles',{exact:true}).check();
    await frame.getByLabel('Watch colors',{exact:true}).selectOption('dark');
    const bounds=await frame.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,height:document.body.scrollHeight}));
    assert.equal(bounds.width,bounds.scroll);assert.deepEqual(errors,[]);
    await frame.getByLabel('Show changing triangles',{exact:true}).uncheck();
    await frame.getByLabel('Minute change',{exact:true}).selectOption('12:59');
    await frame.getByLabel('Watch colors',{exact:true}).selectOption('paper');
    await frame.getByLabel('Animation position',{exact:true}).fill('180');
    await page.locator('iframe').evaluate((el,h)=>el.style.height=h+'px',bounds.height+30);
    await page.screenshot({path:`output/minute-flip-study/preview-${width}-${scheme}.png`,fullPage:true,animations:'allow'});
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.clock.runFor(20);
    await expect(root,'enabling reduced motion settles the current frame').toHaveAttribute('data-elapsed','400');
    await frame.getByRole('button',{name:'Replay 400 ms'}).click();
    assert.equal(await root.getAttribute('data-running'),'false');assert.equal(await root.getAttribute('data-elapsed'),'400');
    reports.push({width,scheme,...bounds,errors,replayCompletes:true});await page.close();
  }
}finally{await browser.close();}
writeFileSync('output/minute-flip-study/check-results.json',JSON.stringify(reports,null,2));
console.log(JSON.stringify(reports,null,2));
