import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdirSync,readFileSync} from 'node:fs';
import vm from 'node:vm';
import {encodePalette} from '../shared/palette-protocol.js';
import {encodeFooter} from '../shared/panel-protocol.js';
import {pebbleColor} from '../shared/settings.js';

mkdirSync('test-results',{recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1100},timezoneId:'America/New_York'});
page.setDefaultTimeout(10000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('dymaxion-workshop-v1')));
const namePalette=async(target,name)=>{await target.getByLabel('Palette name',{exact:true}).fill(name);await target.getByLabel('Palette name',{exact:true}).press('Tab');};
const pixel=async(x,y)=>page.locator('#screen').evaluate((c,[x,y])=>Array.from(c.getContext('2d').getImageData(x,y,1,1).data),[x,y]);
try{
  await page.goto(process.env.PREVIEW_URL||'http://127.0.0.1:5173');
  await page.waitForFunction(()=>document.querySelector('#preview-time').textContent.includes('LIVE'));
  await page.getByRole('tab',{name:'Character',exact:true}).click();
  await page.getByRole('button',{name:'New custom palette',exact:true}).click();
  await namePalette(page,'My ocean');
  await page.getByLabel('Palette background',{exact:true}).fill('#002c60');
  await page.getByLabel('Palette lettering',{exact:true}).fill('#aaffff');
  assert.equal((await saved()).customPalette,0);
  assert.equal((await saved()).customPalettes[0].bg,'#005555');
  assert.deepEqual(await pixel(199,17),[0,85,85,255],'the background changes immediately');
  await page.getByText('Map & night colors',{exact:true}).click();
  await page.getByLabel('Palette day land',{exact:true}).fill('#aaffaa');
  await page.getByLabel('Palette night ocean',{exact:true}).fill('#000000');
  await page.getByText('Places & small indicators',{exact:true}).click();
  await page.getByLabel('Palette place 1 default',{exact:true}).fill('#ffffaa');
  await page.getByText('Chart & calendar defaults',{exact:true}).click();
  await page.getByLabel('Palette rain',{exact:true}).fill('#aaffff');
  let s=await saved();assert.equal(s.customPalettes[0].panelColors.rain,'#AAFFFF');
  const colors=await page.locator('#screen').evaluate(c=>{
    const data=c.getContext('2d').getImageData(0,0,200,228).data,seen=new Set();let blended=0;
    for(let i=0;i<data.length;i+=4){if(data[i]%85||data[i+1]%85||data[i+2]%85||data[i+3]!==255)blended++;seen.add([data[i],data[i+1],data[i+2]].join(','));}
    return {blended,colors:[...seen]};
  });
  assert.equal(colors.blended,0);assert(colors.colors.includes('170,255,170'),'custom land reaches map pixels');
  assert(colors.colors.includes('170,255,255'),'custom lettering reaches the clock');
  await page.getByRole('button',{name:'TWA',exact:true}).click();
  assert.equal((await saved()).customPalette,null);assert.equal((await saved()).customPalettes[0].name,'My ocean');
  await page.getByLabel('Saved custom palette',{exact:true}).selectOption('0');
  await page.getByRole('button',{name:'New custom palette',exact:true}).click();
  await namePalette(page,'Warm draft');await page.getByLabel('Palette lettering',{exact:true}).fill('#ffffaa');
  assert.equal((await saved()).customPalettes[0].ink,'#AAFFFF','editing a duplicate preserves the original');
  await page.getByRole('button',{name:'Delete palette',exact:true}).click();
  assert.equal((await saved()).customPalettes.length,1);assert.equal((await saved()).customPalette,null);
  await page.getByLabel('Saved custom palette',{exact:true}).selectOption('0');
  await page.reload();await page.waitForFunction(()=>document.querySelector('#preview-time').textContent.includes('LIVE'));
  s=await saved();assert.equal(s.customPalette,0);assert.equal(s.customPalettes[0].name,'My ocean');
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export settings'}).click();
  await (await download).saveAs('test-results/custom-palette-export.json');
  assert.deepEqual(JSON.parse(readFileSync('test-results/custom-palette-export.json','utf8')),s);
  await page.locator('#reset').click();await page.locator('#import-file').setInputFiles('test-results/custom-palette-export.json');
  await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Composition imported.');assert.deepEqual(await saved(),s);
  await page.getByRole('tab',{name:'Character',exact:true}).click();
  await page.screenshot({path:'test-results/custom-palettes-designer.png',fullPage:true});
  await page.locator('#screen').screenshot({path:'test-results/custom-palettes-watch.png'});
  // Send the exported library through the actual companion and its offline phone form.
  const handlers={},messages=[],store=new Map();let opened='';
  const context={console,Date,Math,Uint8Array,DataView,Array,Object,JSON,Number,String,RegExp,parseInt,parseFloat,isNaN,isFinite,decodeURIComponent,encodeURIComponent,setTimeout:fn=>{fn();return 1;},clearTimeout:()=>{},
    localStorage:{getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)},
    Pebble:{addEventListener:(event,fn)=>handlers[event]=fn,openURL:url=>opened=url,sendAppMessage:(message,success)=>{messages.push(message);success();}}};
  vm.runInNewContext(readFileSync('watchface/src/pkjs/index.js','utf8'),context);
  handlers.webviewclosed({response:encodeURIComponent(JSON.stringify(s))});
  let packet=messages.findLast(m=>m.SETTINGS);
  assert.deepEqual(Array.from(packet.PALETTE),[...encodePalette(s)]);
  assert.deepEqual(Array.from(packet.FOOTER),[...encodeFooter(s)]);
  assert.equal(packet.SETTINGS[86],pebbleColor(s.customPalettes[0].marks[0]));
  await handlers.showConfiguration();
  const phone=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:3});phone.on('pageerror',e=>errors.push(e.message));
  await phone.goto(opened);
  await phone.locator('details').evaluateAll(nodes=>nodes.forEach(d=>d.open=true));
  assert.equal(await phone.getByLabel('Palette name',{exact:true}).inputValue(),'My ocean');
  assert.equal(await phone.getByLabel('Color for place 1',{exact:true}).inputValue(),'#ffffaa');
  assert(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await namePalette(phone,'Ocean & <draft>');
  await phone.getByLabel('Palette lettering',{exact:true}).fill('#ffffaa');
  await phone.locator('#theme').selectOption('4');
  await phone.getByLabel('Saved custom palette',{exact:true}).selectOption('0');
  assert.equal(await phone.getByLabel('Palette lettering',{exact:true}).inputValue(),'#ffffaa');
  await phone.screenshot({path:'test-results/custom-palettes-phone.png',fullPage:true});
  const cdp=await phone.context().newCDPSession(phone);await cdp.send('Page.enable');
  const closed=new Promise(resolve=>cdp.on('Page.frameRequestedNavigation',event=>{if(event.url.startsWith('pebblejs://close#'))resolve(event.url);}));
  await phone.getByRole('button',{name:'Save to watch',exact:false}).click();
  let timer;const url=await Promise.race([closed,new Promise((_,reject)=>{timer=setTimeout(()=>reject(new Error('Phone configuration did not return settings')),5000);})]);clearTimeout(timer);
  handlers.webviewclosed({response:url.split('#')[1]});
  const phoneSaved=JSON.parse(store.get('dymaxion-settings-v1'));
  assert.equal(phoneSaved.customPalettes[0].name,'Ocean & <draft>');assert.equal(phoneSaved.customPalettes[0].ink,'#FFFFAA');
  assert.deepEqual(Array.from(messages.findLast(m=>m.PALETTE).PALETTE),[...encodePalette(phoneSaved)]);
  await handlers.showConfiguration();await phone.goto(opened);
  await phone.locator('details').evaluateAll(nodes=>nodes.forEach(d=>d.open=true));
  assert.equal(await phone.getByLabel('Palette name',{exact:true}).inputValue(),'Ocean & <draft>','palette names round trip through escaped inline configuration');
  phoneSaved.customPalette=null;handlers.webviewclosed({response:JSON.stringify(phoneSaved)});
  assert.equal(messages.findLast(m=>m.PALETTE).PALETTE[2],0,'switching back to a preset reaches the watch');
  assert.equal(JSON.parse(store.get('dymaxion-settings-v1')).customPalettes.length,1);
  assert.deepEqual(errors,[]);
  console.log('PASS: custom palette editing, native pixels, saved library, export/import, phone form and companion packets.');
}finally{await browser.close();}
